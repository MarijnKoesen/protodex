package migratebuf

import (
	"context"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func fixture(t *testing.T) string {
	t.Helper()
	dst := t.TempDir()
	err := filepath.WalkDir("testdata", func(p string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, _ := filepath.Rel("testdata", p)
		b, err := os.ReadFile(p) //nolint:gosec // test fixture paths
		if err != nil {
			return err
		}
		out := filepath.Join(dst, rel)
		if err := os.MkdirAll(filepath.Dir(out), 0o750); err != nil {
			return err
		}
		return os.WriteFile(out, b, 0o600) //nolint:gosec // test fixture paths
	})
	if err != nil {
		t.Fatal(err)
	}
	return dst
}

func read(t *testing.T, p string) string {
	t.Helper()
	b, err := os.ReadFile(p) //nolint:gosec // test fixture paths
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func TestDryRunChangesNothing(t *testing.T) {
	root := fixture(t)
	before := read(t, filepath.Join(root, "v2/buf.yaml"))
	called := false
	res, err := Run(context.Background(), Options{Root: root, From: "buf.build", To: "reg.example.com",
		DepUpdate: func(context.Context, string) error { called = true; return nil }})
	if err != nil {
		t.Fatal(err)
	}
	if called {
		t.Fatal("dry run must not run buf dep update")
	}
	if read(t, filepath.Join(root, "v2/buf.yaml")) != before {
		t.Fatal("dry run modified a file")
	}
	if len(res.Rewrites) != 5 || len(res.UpdateDirs) != 2 {
		t.Fatalf("rewrites=%d dirs=%v", len(res.Rewrites), res.UpdateDirs)
	}
	if !strings.Contains(res.Report(false), "dry run") {
		t.Fatal("report lacks dry-run notice")
	}
}

func TestApply(t *testing.T) {
	root := fixture(t)
	var dirs []string
	res, err := Run(context.Background(), Options{Root: root, From: "buf.build", To: "reg.example.com:8443", Apply: true,
		DepUpdate: func(_ context.Context, d string) error { dirs = append(dirs, d); return nil }})
	if err != nil {
		t.Fatal(err)
	}
	got := read(t, filepath.Join(root, "v2/buf.yaml"))
	for _, want := range []string{
		"name: reg.example.com:8443/acme/api",
		"- reg.example.com:8443/googleapis/googleapis # keep comment",
		`- "reg.example.com:8443/grpc-ecosystem/grpc-gateway:main"`,
		"- other.example.com/x/y",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("buf.yaml missing %q:\n%s", want, got)
		}
	}
	if !strings.Contains(read(t, filepath.Join(root, "v1/buf.yaml")), "name: reg.example.com:8443/acme/legacy") {
		t.Error("v1 module name not rewritten")
	}
	// buf.lock is regenerated by buf dep update, never edited by hand.
	if !strings.Contains(read(t, filepath.Join(root, "v2/buf.lock")), "buf.build/googleapis") {
		t.Error("buf.lock must be left to buf dep update")
	}
	if len(dirs) != 2 || len(res.UpdateDirs) != 2 {
		t.Fatalf("dep update dirs = %v", dirs)
	}
	// Idempotent: a second run finds nothing.
	res, err = Run(context.Background(), Options{Root: root, From: "buf.build", To: "reg.example.com:8443", Apply: true})
	if err != nil || len(res.Rewrites) != 0 {
		t.Fatalf("second run: %v %v", res, err)
	}
}

func TestPluginReport(t *testing.T) {
	root := fixture(t)
	res, err := Run(context.Background(), Options{Root: root, From: "buf.build", To: "r.example.com"})
	if err != nil {
		t.Fatal(err)
	}
	got := map[string]string{}
	for _, p := range res.Plugins {
		got[p.Ref] = p.Local
	}
	want := map[string]string{
		"buf.build/protocolbuffers/go":   "protoc-gen-go",
		"buf.build/connectrpc/es:v1.4.0": "protoc-gen-connect-es",
		"buf.build/some/unknown":         "",
		"buf.build/grpc/go":              "protoc-gen-go-grpc",
	}
	if len(got) != len(want) {
		t.Fatalf("plugins = %v", got)
	}
	for k, v := range want {
		if g, ok := got[k]; !ok || g != v {
			t.Errorf("plugin %s = %q (found %v), want %q", k, g, ok, v)
		}
	}
}

func TestValidation(t *testing.T) {
	for _, o := range []Options{
		{Root: ".", From: "buf.build"},
		{Root: ".", From: "buf.build", To: "https://x"},
		{Root: ".", From: "a", To: "a"},
	} {
		if _, err := Run(context.Background(), o); err == nil {
			t.Errorf("want error for %+v", o)
		}
	}
}
